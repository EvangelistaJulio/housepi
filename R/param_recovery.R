#' Columns the surveys are generated on: covariates and identifiers only.
#' Status, observations and latent variables are regenerated by simulation,
#' and a definition reading one of them must not see the observed value.
#' @noRd
recovery_base_structure_ <- function(hhmodel) {
  data <- hhmodel$data_wide
  if (is.null(data) || nrow(data) == 0L) stop_h(
    "No data is attached to the model.",
    paste("A recovery check generates its surveys on the structure of the",
          "attached data: add one with {.fn add_data_wide}.")
  )
  written <- c("status", hhmodel$observations[["name"]],
               hhmodel$latent[["name"]])
  data[setdiff(names(data), written)]
}

#' Simulation table: every pinned parameter, overridden by `truth`.
#' Mirrors what `run_simulation()` builds from the pins on its own, so the
#' surveys are generated exactly as an ordinary simulation would.
#' @noRd
recovery_param_table_ <- function(hhmodel, truth, point_estimate) {
  defs <- get_parameters(hhmodel)
  pins <- stats::setNames(defs[["value"]], defs[["name"]])
  if (!is.null(truth)) {
    given <- recovery_collapse_truth_(truth, point_estimate)
    hhmodel$.__enclos_env__$private$assert_no_baseline_value_(given, "truth")
    known <- intersect(names(given), names(pins))
    pins[known] <- given[known]
    unknown <- setdiff(names(given), names(pins))
    if (length(unknown)) warn_h(
      "No parameter named {.val {unknown}} in the model.",
      `!` = "Its {.arg truth} value is ignored."
    )
  }
  pins <- pins[!is.na(pins)]
  as.data.frame(as.list(pins), check.names = FALSE)
}

#' Collapse a table of values to one named vector of point estimates.
#' @noRd
recovery_collapse_truth_ <- function(truth, point_estimate) {
  tab <- helper_read_param_table_(truth, thin_ess = FALSE)
  stat <- if (identical(point_estimate, "mean")) mean else stats::median
  vapply(tab, function(x) stat(as.numeric(x)), numeric(1L))
}

#' The parameters a recovery check is about: estimated, hence carrying a prior
#' and free. Every one of them must be pinned, since a parameter absent from
#' the simulation table is drawn from its prior and its recorded truth would
#' be a lie.
#' @noRd
recovery_truth_ <- function(hhmodel, param_table) {
  defs <- get_parameters(hhmodel)
  estimated <- defs[["name"]][!is.na(defs[["prior"]]) &
                                !(defs[["const"]] %in% TRUE)]
  if (length(estimated) == 0L) stop_h(
    "The model holds no parameter to recover.",
    "A recovery check needs a parameter carrying a prior and free to move."
  )
  unpinned <- setdiff(estimated, names(param_table))
  if (length(unpinned)) stop_h(
    "No simulation value for parameter{?s} {.val {unpinned}}.",
    paste("A recovery check simulates at known values: set {.arg value} on",
          "{.fn add_parameter}, the {.field value} column of a strata table,",
          "or pass {.arg truth}.")
  )
  unlist(param_table[estimated])
}

#' Recovery statistics per household count and parameter.
#' @param estimates `data.frame` One row per replicate and parameter.
#' @noRd
recovery_summary_ <- function(estimates) {
  recovery_by_(estimates, c("houses", "variable"), function(d) {
    truth <- d[["truth"]][[1L]]
    error <- d[["estimate"]] - truth
    data.frame(
      d[1L, c("houses", "variable")], truth = truth,
      estimate = mean(d[["estimate"]]), bias = mean(error),
      rel_bias = if (truth == 0) NA_real_ else mean(error) / truth,
      rmse = sqrt(mean(error^2)),
      coverage = mean(d[["cri_lower"]] <= truth & truth <= d[["cri_upper"]]),
      cri_width = mean(d[["cri_upper"]] - d[["cri_lower"]]),
      ess_bulk = mean(d[["ess_bulk"]]),
      nrep = nrow(d), n_flagged = sum(!d[["converged"]])
    )
  })
}

#' Sweep cost per household count, averaged over the replicates.
#' @param replicates `data.frame` One row per replicate.
#' @noRd
recovery_overview_ <- function(replicates) {
  recovery_by_(replicates, "houses", function(d) {
    data.frame(
      houses = d[["houses"]][[1L]], nrep = nrow(d),
      n_failed = sum(!is.na(d[["error"]])),
      n_flagged = sum(d[["converged"]] %in% FALSE),
      mean_inference_seconds = mean(d[["inference_seconds"]], na.rm = TRUE)
    )
  })
}

#' One row of `fun` per group of `cols`, stacked back.
#' @noRd
recovery_by_ <- function(x, cols, fun) {
  recovery_stack_(lapply(split(x, row_keys_(x, cols)), fun), cols)
}

#' Bind rows back into one frame, ordered by the grouping columns.
#' @noRd
recovery_stack_ <- function(parts, cols) {
  out <- do.call(rbind, parts)
  out <- out[do.call(order, out[cols]), , drop = FALSE]
  rownames(out) <- NULL
  out
}

#' Run `fn` on the model re-attached to `data`, with the given arguments.
#' @noRd
recovery_run_ <- function(fn, hhmodel, data, args) {
  do.call(fn, c(list(add_data_wide(hhmodel, data)), args))
}

#' Household counts of the sweep, one cell each.
#' @noRd
recovery_houses_ <- function(structure, houses, verbatim) {
  observed <- length(unique(structure[["hhid"]]))
  if (!verbatim) return(unique(recovery_house_counts_(houses, observed)))
  if (!all(is.na(houses))) warn_h(
    "Argument {.arg houses} is ignored.",
    "A {.code NULL} sampler reuses the attached structure verbatim."
  )
  observed
}

#' Household counts as whole positive numbers, `NA` standing for `observed`.
#' @param one `logical(1)` Demand a single count.
#' @noRd
recovery_house_counts_ <- function(houses, observed, one = FALSE) {
  n <- suppressWarnings(as.integer(houses))
  n[is.na(houses)] <- observed
  ok <- length(n) > 0L && !anyNA(n) && all(n >= 1L) && !(one && length(n) > 1L)
  if (!ok) stop_h("Number of households should be a positive integer.")
  n
}

#' Whether a fit passed both diagnostics, on the predicate that
#' `check_diagnostics_()` warns on. A sample too short for a diagnostic is
#' flagged whole, as the engine skips it entirely.
#' @noRd
recovery_converged_ <- function(summ, sample_size) {
  if (sample_size < diagnostic_[["ss_min"]]) return(rep(FALSE, nrow(summ)))
  good_rhat <- !(round(summ[["rhat"]], 2) > diagnostic_[["rhat_max"]])
  good_ess <- !(summ[["ess_bulk"]] / sample_size < diagnostic_[["neff_min"]])
  (good_rhat %in% TRUE) & (good_ess %in% TRUE)
}

#' Progress bar over the replicate grid, or nothing when it is switched off.
#' The bar of each fit is suppressed, so a sweep prints one bar.
#' @noRd
recovery_progress_bar_ <- function(progress, total) {
  if (!isTRUE(as.logical(progress[[1L]]))) return(NULL)
  cli::cli_progress_bar("Recovery replicates", total = total,
                        .envir = parent.frame())
}

#' Distinct warning messages raised over a sweep, with their counts.
#' @param raised `list` Per-fit warnings, as a fit's `warnings` field holds.
#' @noRd
recovery_warning_counts_ <- function(raised) {
  held <- do.call(rbind, raised)
  if (is.null(held) || nrow(held) == 0L) {
    return(data.frame(message = character(), count = integer()))
  }
  counts <- tapply(held[["count"]], held[["message"]], sum)
  data.frame(message = names(counts), count = as.integer(counts),
             row.names = NULL, stringsAsFactors = FALSE)
}

#' @title Resample the household structure of a survey
#' @description
#' Draw whole households with replacement, so the household-size distribution
#' and the within-household composition of the covariates are preserved while
#' the number of households is scaled.
#' @param data_wide `r rd_add_wide_`
#' @param houses `integer(1)` Number of households to draw.
#' `NA` targets the number of households carried by `data_wide`.
#' @return `data.frame` with `hhid` renumbered sequentially, so a household
#' drawn twice stands as two independent households, and `id` regenerated as
#' a row number when the input carries one.
#' @examples
#' structure <- sample_house_structure(flu_1918_frederick, houses = 20)
#' summarise_house_sizes(new_housepi_model(structure, "final_size"))
#' @export
sample_house_structure <- function(data_wide, houses = NA_integer_) {
  data <- as.data.frame(data_wide)
  if (!"hhid" %in% names(data)) stop_h(
    "Column {.field hhid} is missing from the data.",
    "Provide an household identifier in order to allow sampling."
  )
  blocks <- split(data, data[["hhid"]], drop = TRUE)
  houses <- recovery_house_counts_(houses, length(blocks), one = TRUE)
  drawn <- blocks[sample.int(length(blocks), houses, replace = TRUE)]
  out <- do.call(rbind, drawn)
  rownames(out) <- NULL
  out[["hhid"]] <- rep(seq_along(drawn), vapply(drawn, nrow, integer(1L)))
  if ("id" %in% names(out)) out[["id"]] <- seq_len(nrow(out))
  out
}

#' @title Parameter recovery check of a housepi model
#' @description
#' Container for the sweep run by [run_parameter_recovery_check()]: surveys
#' simulated at known parameter values and fitted back, replicated at one or
#' more household counts.
#' @examples
#' recovery <- flu_1918_frederick |>
#'   new_housepi_model("final-size") |>
#'   add_parameter(import = "template") |>
#'   run_parameter_recovery_check(nrep = 2, houses = 30, progress = FALSE)
#' recovery
#' recovery$summary
#' @docType class
HousepiParameterRecovery <- R6::R6Class(
  classname = "HousepiParameterRecovery",

  ############################################################################
  ################################## PRIVATE #################################
  ############################################################################

  private = list(
    name_ = NA_character_,
    nrep_ = NA_integer_,
    houses_ = NULL,
    truth_ = NULL,
    point_estimate_ = NA_character_,
    cri_level_ = NA_real_,
    estimates_ = NULL,
    replicates_ = NULL,
    warnings_ = NULL,
    sim_args_ = NULL,
    fit_args_ = NULL,

    # The sweep: one simulation call per household count, then one fit per
    # replicate. The fitted model is built from the given model and never
    # from the one that simulated, which holds the truth of the last
    # replicate.
    sweep_ = function(hhmodel, structure, sampler, progress) {
      estimates <- replicates <- raised <- list()
      bar <- recovery_progress_bar_(progress,
                                    length(private$houses_) * private$nrep_)
      for (houses in private$houses_) {
        struct <- structure
        if (!is.null(sampler)) struct <- sampler(structure, houses)
        surveys <- recovery_run_(run_simulation, hhmodel, struct,
                                 private$sim_args_)
        if (is.data.frame(surveys)) surveys <- list(surveys)
        cell <- lapply(seq_len(private$nrep_), function(rep) {
          one <- private$one_replicate_(hhmodel, surveys[[rep]], houses, rep)
          if (!is.null(bar)) cli::cli_progress_update(id = bar)
          one
        })
        rm(surveys)
        done <- Filter(Negate(is.null), lapply(cell, `[[`, "estimates"))
        # an engine message carries no markup: interpolate, never inline
        reason <- cell[[1L]]$replicate[["error"]]
        if (length(done) == 0L) stop_h(
          "Every replicate failed at {.val {houses}} households.",
          `!` = "{reason}"
        )
        estimates <- c(estimates, done)
        replicates <- c(replicates, lapply(cell, `[[`, "replicate"))
        raised <- c(raised, lapply(cell, `[[`, "warnings"))
      }
      list(estimates = estimates, replicates = replicates,
           warnings = recovery_warning_counts_(raised))
    },

    # One replicate: the survey's secondary attack rate, then the fit.
    # A replicate that fails is recorded and the sweep carries on.
    one_replicate_ = function(hhmodel, simulated, houses, rep) {
      failure <- NA_character_
      fit <- tryCatch(
        private$fit_one_(hhmodel, simulated, houses, rep),
        error = function(e) {
          failure <<- conditionMessage(e)
          NULL
        }
      )
      list(
        estimates = fit$estimates,
        warnings = fit$warnings,
        replicate = data.frame(
          houses = houses, rep = rep,
          inference_seconds = if (is.null(fit)) NA_real_ else fit$seconds,
          converged = if (is.null(fit)) NA else all(fit$estimates$converged),
          error = failure
        )
      )
    },

    # Fit one survey back and summarise its draws.
    # Kept whole and free of sweep state, so it can be mapped later.
    fit_one_ = function(hhmodel, simulated, houses, rep) {
      latent <- intersect(hhmodel$latent[["name"]], names(simulated))
      hhdata <- simulated[setdiff(names(simulated), latent)]
      draws <- recovery_run_(run_inference, hhmodel, hhdata,
                             private$fit_args_)
      list(estimates = cbind(houses = houses, rep = rep,
                             private$summarise_draws_(draws)),
           warnings = draws$warnings,
           seconds = draws$inference_seconds)
    },

    # Point estimate, credible interval and sampler cost per parameter.
    summarise_draws_ = function(draws) {
      stat <- switch(private$point_estimate_, mean = mean, stats::median)
      probs <- cri_level_probs(private$cri_level_)
      pdraws <- get_parameter_draws(draws)
      summ <- as.data.frame(posterior::summarise_draws(
        pdraws,
        estimate = stat,
        cri_lower = function(x) unname(stats::quantile(x, probs[["lower"]])),
        cri_upper = function(x) unname(stats::quantile(x, probs[["upper"]])),
        rhat = posterior::rhat, ess_bulk = posterior::ess_bulk
      ))
      summ <- summ[summ[["variable"]] %in% names(private$truth_), ]
      sample_size <- posterior::niterations(pdraws) * posterior::nchains(pdraws)
      cbind(
        summ["variable"],
        truth = unname(private$truth_[summ[["variable"]]]),
        summ[c("estimate", "cri_lower", "cri_upper", "rhat", "ess_bulk")],
        converged = recovery_converged_(summ, sample_size)
      )
    },

    # One warning per distinct message, with the count of replicates that
    # raised it. Foreign text carries no markup.
    report_warnings_ = function() {
      if (is.null(private$warnings_) || nrow(private$warnings_) == 0L) return()
      n_warn <- nrow(private$warnings_)
      lines <- mapply(function(n, msg) inline_cli_("{n} replicate{?s}: {msg}"),
                      private$warnings_[["count"]],
                      private$warnings_[["message"]])
      header <- inline_cli_(
        "Parameter recovery raised {n_warn} distinct warning{?s}."
      )
      bullets <- stats::setNames(lines, rep("!", length(lines)))
      emit_cli_condition(c(list(header), as.list(bullets)), "warn")
    }
  ),

  ############################################################################
  ################################## ACTIVE ##################################
  ############################################################################

  active = list(
    #' @field estimates `data.frame`
    #' One row per household count, replicate and parameter
    #' \describe{
    #'   \item{truth}{Value the survey was simulated at}
    #'   \item{estimate}{Posterior point estimate}
    #'   \item{cri_lower, cri_upper}{Credible interval bounds}
    #'   \item{rhat, ess_bulk}{Convergence diagnostics of the fit}
    #'   \item{converged}{Whether the fit passed both diagnostics}
    #' }
    estimates = function(value) {
      if (!missing(value)) stop_read_only("estimates")
      private$estimates_
    },

    #' @field replicates `data.frame`
    #' One row per household count and replicate
    #' \describe{
    #'   \item{inference_seconds}{Wall-clock of the sampling loop}
    #'   \item{converged}{Whether every parameter passed both diagnostics}
    #'   \item{error}{Message of a replicate that failed, else `NA`}
    #' }
    replicates = function(value) {
      if (!missing(value)) stop_read_only("replicates")
      private$replicates_
    },

    #' @field summary `data.frame`
    #' Recovery statistics per household count and parameter
    #' \describe{
    #'   \item{bias, rel_bias}{Mean error, absolute and relative to the truth}
    #'   \item{rmse}{Root mean squared error}
    #'   \item{coverage}{Share of replicates whose interval covers the truth}
    #'   \item{cri_width}{Mean width of the credible interval}
    #'   \item{nrep, n_flagged}{Replicates aggregated, and those flagged}
    #' }
    summary = function(value) {
      if (!missing(value)) stop_read_only("summary")
      recovery_summary_(private$estimates_)
    },

    #' @field overview `data.frame`
    #' Sweep cost per household count, averaged over the replicates
    #' \describe{
    #'   \item{nrep, n_failed, n_flagged}{Replicates run, failed and flagged}
    #'   \item{mean_inference_seconds}{Mean wall-clock of a sampling loop}
    #' }
    overview = function(value) {
      if (!missing(value)) stop_read_only("overview")
      recovery_overview_(private$replicates_)
    },

    #' @field truth named `numeric()`
    #' Values the surveys were simulated at.
    truth = function(value) {
      if (!missing(value)) stop_read_only("truth")
      private$truth_
    },

    #' @field houses `integer()`
    #' Household counts swept.
    houses = function(value) {
      if (!missing(value)) stop_read_only("houses")
      private$houses_
    },

    #' @field nrep `integer(1)`
    #' Replicates run at each household count.
    nrep = function(value) {
      if (!missing(value)) stop_read_only("nrep")
      private$nrep_
    },

    #' @field point_estimate `character(1)`
    #' Summary statistic taken as the posterior point estimate.
    point_estimate = function(value) {
      if (!missing(value)) stop_read_only("point_estimate")
      private$point_estimate_
    },

    #' @field cri_level `numeric(1)`
    #' Credible level the intervals and the coverage are computed at.
    cri_level = function(value) {
      if (!missing(value)) stop_read_only("cri_level")
      private$cri_level_
    },

    #' @field warnings `data.frame`
    #' Distinct warnings raised over the sweep, with their counts.
    warnings = function(value) {
      if (!missing(value)) stop_read_only("warnings")
      private$warnings_
    }
  ),

  ############################################################################
  ################################## PUBLIC ##################################
  ############################################################################

  public = list(
    #' @description
    #' Internal: [run_parameter_recovery_check()] builds this object, don't
    #' call `$new()` directly.
    #' @param hhmodel `r rd_model_in_`
    #' @param nrep `r rd_recov_nrep_`
    #' @param houses `r rd_recov_houses_`
    #' @param structure_sampler `r rd_recov_sampler_`
    #' @param truth `r rd_recov_truth_`
    #' @param steps `r rd_smpl_steps_`
    #' @param burn `r rd_smpl_burn_`
    #' @param thin `r rd_smpl_thin_`
    #' @param adapt `r rd_smpl_adapt_`
    #' @param chains `r rd_smpl_chain_`
    #' @param threads `r rd_thread_`
    #' @param progress `logical(1)` Whether to show a progress bar over the
    #' replicates. The progress of each fit is always suppressed.
    #' @param ... `r rd_dots_config_`
    initialize = function(hhmodel, nrep = 50L, houses = NA_integer_,
                          structure_sampler = sample_house_structure,
                          truth = NULL, steps = 1000L, burn = 0L,
                          thin = 5L, adapt = 500L,
                          chains = 4L, threads = 1L,
                          progress = TRUE, ...) {
      if (!rlang::is_scalar_integerish(nrep) || is.na(nrep) || nrep < 1) stop_h(
        "Number of replicates should be a positive integer."
      )
      private$nrep_ <- as.integer(nrep)
      private$point_estimate_ <- get_global_point_estimate()
      private$cri_level_ <- get_global_cri_level()
      private$name_ <- hhmodel$.__enclos_env__$private$gen_$raw_name

      pins <- recovery_param_table_(hhmodel, truth, private$point_estimate_)
      private$truth_ <- recovery_truth_(hhmodel, pins)
      structure <- recovery_base_structure_(hhmodel)
      private$houses_ <- recovery_houses_(structure, houses,
                                          is.null(structure_sampler))

      dots <- list(...)
      # one simulation call per household count yields the whole cell: the
      # pins are repeated, one row per replicate
      private$sim_args_ <- c(
        list(param_table = pins[rep(1L, private$nrep_), , drop = FALSE]),
        dots[names(dots) == "time_step"]
      )
      private$fit_args_ <- c(
        list(steps = steps, burn = burn, thin = thin, adapt = adapt,
             chains = chains, threads = threads, progress = FALSE,
             warn = FALSE),
        dots[names(dots) == "adapt_window"]
      )
      swept <- private$sweep_(hhmodel, structure, structure_sampler, progress)
      private$estimates_ <- recovery_stack_(swept$estimates,
                                            c("houses", "rep"))
      private$replicates_ <- recovery_stack_(swept$replicates,
                                             c("houses", "rep"))
      private$warnings_ <- swept$warnings
      private$report_warnings_()
      invisible(self)
    },

    #' @description Override the default printing behavior.
    print = function() {
      model <- spaced_template_choice(private$name_)
      failed <- sum(!is.na(private$replicates_[["error"]]))
      flagged <- sum(private$replicates_[["converged"]] %in% FALSE)
      print_bullets(c(
        i = "Parameter recovery check of model {.val {model}}.",
        "Households: {.val {private$houses_}}. \\
         Replicates each: {private$nrep_}.",
        "Point estimate: {.val {private$point_estimate_}}. \\
         Credible level: {.val {private$cri_level_}}.",
        "Replicates failed: {failed}. Flagged by diagnostics: {flagged}."
      ))
      invisible(self)
    }
  )
)

#' @title Check that inference recovers known parameters
#' @description
#' Simulate surveys at known parameter values, fit each one back with the same
#' model, and report how well the posterior recovers the values that generated
#' it. The sweep is repeated at one or more household counts, which is what
#' shows whether a bias shrinks with the size of the study.
#'
#' The parameter pins of the model are the values the surveys are simulated
#' at, and the priors of the very same model drive inference, so no separate
#' simulation model is needed.
#' @param hhmodel `r rd_model_in_`
#' @param nrep `r rd_recov_nrep_`
#' @param houses `r rd_recov_houses_`
#' @param structure_sampler `r rd_recov_sampler_`
#' @param truth `r rd_recov_truth_`
#' @param steps `r rd_smpl_steps_`
#' @param burn `r rd_smpl_burn_`
#' @param thin `r rd_smpl_thin_`
#' @param adapt `r rd_smpl_adapt_`
#' @param chains `r rd_smpl_chain_`
#' @param threads `r rd_thread_`
#' @param progress `logical(1)` Whether to show a progress bar over the
#' replicates. The progress of each fit is always suppressed.
#' @param ... `r rd_dots_config_`
#' @return An object of class [HousepiParameterRecovery].
#' @details
#' A replicate that fails is recorded and the sweep carries on; a household
#' count whose every replicate failed raises an error.
#' `r rd_global_summary_`
#' `r rd_recov_seed_`
#' @examples
#' recovery <- flu_1918_frederick |>
#'   new_housepi_model("final-size") |>
#'   add_parameter(import = "template") |>
#'   run_parameter_recovery_check(nrep = 2, houses = 30, progress = FALSE)
#' recovery$summary
#' recovery$overview
#' @export
run_parameter_recovery_check <- function(hhmodel,
                                         nrep = 50L,
                                         houses = NA_integer_,
                                         structure_sampler =
                                           sample_house_structure,
                                         truth = NULL,
                                         steps = 1000L, burn = 0L,
                                         thin = 5L, adapt = 500L,
                                         chains = 4L, threads = 1L,
                                         progress = TRUE,
                                         ...) {
  stopifnothousepi(hhmodel)
  assert_advanced_setup_(c("adapt_window", "time_step"), ...)
  HousepiParameterRecovery$new(
