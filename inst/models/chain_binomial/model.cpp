/// [CHANGE-ME] Risk of infection from the community.
double Model::community_risk() const { return param("alpha"); }

/// [CHANGE-ME] Risk of infection from another household member.
double Model::person_to_person_risk() const { return param("beta"); }

///////////////////////////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////  Model : simulate single house  //////////////////////////////////
///////////////////////////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////////////////////////

/// Simulate the infection within a household.
void Model::simulate_single_household(Household &house)
{
	double commu_esc_proba = exp(-community_risk());
	double log_p2p_esc_proba = -person_to_person_risk();

	//////////////////////////////////////////////////////////////////
	/////////////  Generation 0 : infection by community  ////////////
	//////////////////////////////////////////////////////////////////

	for (Individual &member : house)
		if (uniform() < commu_esc_proba)
			house.change_status(member, HSP_HEALTHY_STATUS);
		else
			house.change_status(member, HSP_INFECTED_STATUS);

	//////////////////////////////////////////////////////////////////
	//////  Generation >=1 : infection by previous generation  ///////
	//////////////////////////////////////////////////////////////////

	size_t n_old_gen = 0;
	size_t n_new_gen = house.n_infec_status();

	while ((house.n_infec_status() > 0) && (n_new_gen > 0))
	{
		n_old_gen = n_new_gen;
		n_new_gen = 0;

		for (Individual &member : house.healthy())
			if (uniform() >= exp(n_old_gen * log_p2p_esc_proba))
			{
				house.change_status(member, HSP_INFECTED_STATUS);
				++n_new_gen;
			}
	}
}
